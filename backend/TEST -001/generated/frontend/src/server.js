import express from 'express';

const app = express();
app.use(express.json());

const PORT = process.env.PORT || 3000;
const SERVICE_NAME = "frontend";

app.get("/health", (_req, res) => res.json({ status: 'ok', service: SERVICE_NAME }));
app.get('/ready', (_req, res) => res.json({ status: 'ready', service: SERVICE_NAME }));

app.get('/', (_req, res) => {
  res.json({
    service: SERVICE_NAME,
    type: "frontend",
    dependsOn: [],
    message: 'Generated by KubeVerse from architecture.md',
  });
});

app.listen(PORT, () => {
  console.log(JSON.stringify({ level: 'info', service: SERVICE_NAME, msg: `listening on port ${PORT}` }));
});
